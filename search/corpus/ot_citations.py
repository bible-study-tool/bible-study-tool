"""Deterministic Old Testament Citation Anchors in the New Testament (WP-026).

Implements Scripture-interpreting-Scripture cross-referencing by cataloging canonical
Old Testament quotations, prophetic fulfillments, and covenant anchors quoted by apostolic
writers (Paul, Peter, Hebrews, Gospels, Acts).

Every entry pairs:
- NT OSIS reference & apostolic introductory formula (e.g. 'καθὼς γέγραπται')
- OT OSIS reference & original Hebrew WLC text
- Septuagint (LXX) textual variation where relevant
- Covenant theme and deep theological exposition of how apostolic theology builds upon the OT bedrock.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Any
from rich.markup import escape


class CitationType(str, Enum):
    """Classification of how an Old Testament passage is employed in the New Testament."""
    DIRECT_QUOTE = "DIRECT_QUOTE"                  # Verbatim or near-verbatim citation
    PROPHETIC_FULFILLMENT = "PROPHETIC_FULFILLMENT"  # Explicit fulfillment formula ("that it might be fulfilled")
    ALLUSION = "ALLUSION"                          # Clear verbal and conceptual dependency
    COVENANT_TYPOLOGY = "COVENANT_TYPOLOGY"        # Structural sanctuary/covenant/priesthood typology


@dataclass(frozen=True)
class OTCitation:
    """Deterministic representation of an OT quotation or major covenant anchor in the NT."""
    nt_osis: str                    # e.g. "Rom.1.17"
    ot_osis: str                    # e.g. "Hab.2.4"
    ot_book: str                    # e.g. "Habakkuk"
    ot_ref_display: str             # e.g. "Habakkuk 2:4"
    nt_ref_display: str             # e.g. "Romans 1:17"
    citation_type: CitationType
    introductory_formula: str       # e.g. "καθὼς γέγραπται (As it is written)"
    nt_text_snippet: str            # e.g. "The just shall live by faith."
    ot_text_kjv: str                # e.g. "The just shall live by his faith."
    ot_hebrew: str                  # Hebrew WLC text
    lxx_reading: str                # Septuagint Greek text (if pertinent)
    covenant_theme: str             # e.g. "Righteousness by Faith / Covenant Trust"
    theological_significance: str   # Deep exposition of apostolic theological grounding


