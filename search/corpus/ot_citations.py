# ---------------------------------------------------------------------------
# Indexes for Sub-Millisecond Bidirectional Lookups
# ---------------------------------------------------------------------------

_NT_INDEX: dict[str, list[OTCitation]] = {}
_OT_INDEX: dict[str, list[OTCitation]] = {}

for _cit in _CANONICAL_CITATIONS:
    # 1. NT OSIS Index
    if _cit.nt_osis not in _NT_INDEX:
        _NT_INDEX[_cit.nt_osis] = []
    _NT_INDEX[_cit.nt_osis].append(_cit)

    # 2. OT OSIS Index
    if _cit.ot_osis not in _OT_INDEX:
        _OT_INDEX[_cit.ot_osis] = []
    _OT_INDEX[_cit.ot_osis].append(_cit)


def lookup_ot_citations_for_nt_verse(nt_osis: str) -> list[OTCitation]:
    """Return all Old Testament citations present in a given New Testament verse (e.g. 'Rom.1.17')."""
    return _NT_INDEX.get(nt_osis, [])


def lookup_nt_citations_for_ot_verse(ot_osis: str) -> list[OTCitation]:
    """Return all New Testament passages citing or anchoring to a given Old Testament verse (e.g. 'Hab.2.4')."""
    return _OT_INDEX.get(ot_osis, [])


def lookup_citations_for_verse(osis_ref: str) -> list[OTCitation]:
    """Bidirectional lookup: returns citations whether the verse is New Testament or Old Testament."""
    if not osis_ref:
        return []
    # Check NT first
    nt_hits = _NT_INDEX.get(osis_ref)
    if nt_hits:
        return nt_hits
    # Check OT
    return _OT_INDEX.get(osis_ref, [])


def get_passage_ot_citations_batch(book: str, chapter: int) -> dict[str, list[OTCitation]]:
    """Batch-fetch all OT citations or NT anchors across an entire chapter in a single pass."""
    batch: dict[str, list[OTCitation]] = {}
    prefix = f"{book}.{chapter}."

    for osis, cits in _NT_INDEX.items():
        if osis.startswith(prefix):
            batch[osis] = list(cits)

    for osis, cits in _OT_INDEX.items():
        if osis.startswith(prefix):
            if osis in batch:
                batch[osis].extend(cits)
            else:
                batch[osis] = list(cits)

    return batch


def format_citation_badge(citation: OTCitation, for_verse_osis: str) -> str:
    """Format a compact, color-coded badge for verse headers in the Reader pane."""
    v_book = for_verse_osis.split(".")[0] if "." in for_verse_osis else for_verse_osis
    nt_book = citation.nt_osis.split(".")[0]
    is_nt = (v_book == nt_book)
    if is_nt:
        return f"[bold green]⟨OT Anchor: {escape(citation.ot_ref_display)}⟩[/bold green]"
    else:
        return f"[bold cyan]⟨Cited in NT: {escape(citation.nt_ref_display)}⟩[/bold cyan]"


def render_citation_card(citation: OTCitation, for_verse_osis: str = "") -> str:
    """Render an in-depth theological card for the workstation inspector."""
    lines: list[str] = []
    v_book = for_verse_osis.split(".")[0] if "." in for_verse_osis else ""
    is_ot = bool(v_book and v_book == citation.ot_osis.split(".")[0])
    header = "CITED IN NEW TESTAMENT" if is_ot else "OT CITATION ANCHOR"
    lines.append(f"[bold green]═══ SCRIPTURE INTERPRETING SCRIPTURE: {header} ═══[/bold green]")
    lines.append(f"[bold yellow]New Testament Reference:[/bold yellow] [bold white]{escape(citation.nt_ref_display)}[/bold white]")
    lines.append(f"[bold yellow]Old Testament Source:[/bold yellow]    [bold cyan]{escape(citation.ot_ref_display)}[/bold cyan] [dim]({citation.citation_type.value})[/dim]")
    lines.append(f"[bold yellow]Apostolic Formula:[/bold yellow]      [italic green]{escape(citation.introductory_formula)}[/italic green]")
    lines.append(f"[bold yellow]Covenant Theme:[/bold yellow]         [bold magenta]{escape(citation.covenant_theme)}[/bold magenta]\n")

    lines.append("[bold underline]Textual Comparison:[/bold underline]")
    lines.append(f"  [bold]NT Apostolic Text:[/bold] [italic]\"{escape(citation.nt_text_snippet)}\"[/italic]")
    lines.append(f"  [bold]OT Hebrew Source:[/bold]  [italic]\"{escape(citation.ot_text_kjv)}\"[/italic]")
    if citation.ot_hebrew:
        lines.append(f"    [dim]WLC Hebrew:[/dim] [bold green]{escape(citation.ot_hebrew)}[/bold green]")
    if citation.lxx_reading:
        lines.append(f"    [dim]Septuagint (LXX):[/dim] [cyan]{escape(citation.lxx_reading)}[/cyan]")
    lines.append("")

    lines.append("[bold underline]Apostolic Hermeneutic & Covenant Theology:[/bold underline]")
    lines.append(f"  {escape(citation.theological_significance)}")
    lines.append("")
    return "\n".join(lines)
